/**
 * Hand-written protobuf (proto3) codec for the messages in `shared_contracts`, plus the JSON
 * payload schemas that ride inside `Command.payload`.
 *
 * Deliberately hand-written instead of protoc-generated: the messages are three flat records
 * with no nesting, and a generated toolchain would add a build step (and a protoc download) to
 * a project whose whole point is that `./gradlew assembleRelease` works on the lab laptop.
 *
 * Rules that must not drift, because 17 subjects' data already exists in this shape:
 *  - proto3 default values are OMITTED on the wire (a zero float, a zero varint, an empty
 *    string produce no bytes at all);
 *  - negative int64 is the canonical 10-byte two's complement varint;
 *  - decoders skip unknown field numbers and unknown (but well-formed) wire types instead of
 *    failing, so a newer backend can add fields without bricking the phones in the field.
 *
 * Everything here is pure Kotlin/JVM with no Android imports, so it runs in a plain unit test
 * and is cross-checked against the backend's own Python decoder via `proto_vectors.json`
 * (generated by `tools/gen_proto_vectors.py`).
 */

/** Raised for a frame that cannot be parsed. Callers drop the frame; they never crash. */
class ProtoDecodeException(message: String) : Exception(message)

// ── writer ──────────────────────────────────────────────────────────────────

class ProtoWriter(initialCapacity: Int = 64) {
    private val out = ByteArrayOutputStream(initialCapacity)

    /** int64 / uint64 / uint32 / enum — wire type 0. Omitted when [value] is 0. */
    fun varintField(field: Int, value: Long): ProtoWriter {
        if (value == 0L) return this
        writeTag(field, WIRE_VARINT)
        writeRawVarint64(value)
        return this
    }

    fun varintField(field: Int, value: Int): ProtoWriter = varintField(field, value.toLong())

    /** float — wire type 5, little-endian IEEE-754. Omitted when [value] is 0.0f. */
    fun floatField(field: Int, value: Float): ProtoWriter {
        // -0.0f == 0.0f, so a negative zero is treated as the default and omitted, exactly
        // like every conforming proto3 encoder.
        if (value == 0.0f) return this
        writeTag(field, WIRE_FIXED32)
        val bits = java.lang.Float.floatToRawIntBits(value)
        out.write(bits and 0xFF)
        out.write((bits ushr 8) and 0xFF)
        out.write((bits ushr 16) and 0xFF)
        out.write((bits ushr 24) and 0xFF)
        return this
    }

    /** string — wire type 2, UTF-8. Omitted when [value] is empty. */
    fun stringField(field: Int, value: String): ProtoWriter {
        if (value.isEmpty()) return this
        val bytes = value.toByteArray(StandardCharsets.UTF_8)
        writeTag(field, WIRE_LENGTH_DELIMITED)
        writeRawVarint64(bytes.size.toLong())
        out.write(bytes, 0, bytes.size)
        return this
    }

    /** bytes — wire type 2. Omitted when empty. */
    fun bytesField(field: Int, value: ByteArray): ProtoWriter {
        if (value.isEmpty()) return this
        writeTag(field, WIRE_LENGTH_DELIMITED)
        writeRawVarint64(value.size.toLong())
        out.write(value, 0, value.size)
        return this
    }

    private fun writeTag(field: Int, wireType: Int) = writeRawVarint64(((field shl 3) or wireType).toLong())

    /**
     * Writes the unsigned 64-bit pattern of [value]. For a negative int64 this yields the
     * canonical 10-byte two's complement form (`ushr` fills with zeroes), which is what the
     * backend's decoder and every protobuf implementation expect.
     */
    private fun writeRawVarint64(value: Long) {
        var v = value
        while (true) {
            if (v and 0x7FL.inv() == 0L) {
                out.write(v.toInt() and 0x7F)
                return
            }
            out.write(((v.toInt() and 0x7F) or 0x80))
            v = v ushr 7
        }
    }

    fun toByteArray(): ByteArray = out.toByteArray()
}

// ── reader ──────────────────────────────────────────────────────────────────

class ProtoReader(private val data: ByteArray) {
    var pos: Int = 0
        private set

    val isAtEnd: Boolean get() = pos >= data.size

    /** Reads a tag, or returns 0 when the frame is exhausted. */
    fun readTag(): Int {
        if (isAtEnd) return 0
        val v = readRawVarint64()
        if (v == 0L) throw ProtoDecodeException("invalid tag 0 at $pos")
        // A real tag is (field << 3) | wire and always fits in a positive Int; anything else
        // means the frame is corrupt or not a protobuf at all.
        if (v <= 0 || v > Int.MAX_VALUE.toLong()) throw ProtoDecodeException("tag out of range: $v")
        return v.toInt()
    }

    fun readVarint64(): Long = readRawVarint64()

    fun readFloat(): Float {
        requireBytes(4)
        val bits = (data[pos].toInt() and 0xFF) or
            ((data[pos + 1].toInt() and 0xFF) shl 8) or
            ((data[pos + 2].toInt() and 0xFF) shl 16) or
            ((data[pos + 3].toInt() and 0xFF) shl 24)
        pos += 4
        return java.lang.Float.intBitsToFloat(bits)
    }

    fun readDouble(): Double {
        requireBytes(8)
        var bits = 0L
        for (i in 7 downTo 0) bits = (bits shl 8) or (data[pos + i].toLong() and 0xFF)
        pos += 8
        return java.lang.Double.longBitsToDouble(bits)
    }

    fun readBytes(): ByteArray {
        val len = readRawVarint64()
        if (len < 0 || len > (data.size - pos).toLong()) {
            throw ProtoDecodeException("length-delimited field runs past the frame ($len)")
        }
        val n = len.toInt()
        val out = data.copyOfRange(pos, pos + n)
        pos += n
        return out
    }

    fun readString(): String = String(readBytes(), StandardCharsets.UTF_8)

    /**
     * Skips a field this codec does not know. Returns false for a wire type it cannot skip
     * (start/end group, which proto3 does not use), in which case the caller stops parsing —
     * the same behaviour as the backend's Python decoder.
     */
    fun skipField(wireType: Int): Boolean = when (wireType) {
        WIRE_VARINT -> {
            readRawVarint64(); true
        }
        WIRE_FIXED64 -> {
            requireBytes(8); pos += 8; true
        }
        WIRE_LENGTH_DELIMITED -> {
            readBytes(); true
        }
        WIRE_FIXED32 -> {
            requireBytes(4); pos += 4; true
        }
        else -> false
    }

    private fun requireBytes(n: Int) {
        if (data.size - pos < n) throw ProtoDecodeException("truncated frame at $pos (need $n)")
    }

    private fun readRawVarint64(): Long {
        var result = 0L
        var shift = 0
        while (true) {
            if (pos >= data.size) throw ProtoDecodeException("truncated varint at $pos")
            val b = data[pos++].toInt()
            if (shift >= 64) throw ProtoDecodeException("varint longer than 10 bytes")
            result = result or ((b.toLong() and 0x7F) shl shift)
            if (b and 0x80 == 0) return result
            shift += 7
        }
    }

    companion object {
        fun fieldOf(tag: Int): Int = tag ushr 3
        fun wireOf(tag: Int): Int = tag and 0x7
    }
}

const val WIRE_VARINT = 0
const val WIRE_FIXED64 = 1
const val WIRE_LENGTH_DELIMITED = 2
const val WIRE_FIXED32 = 5

// ── SensorPacket ────────────────────────────────────────────────────────────

/**
 * `shared_contracts/sensor_packet.proto`. acc_* are g, gyro_* are deg/s.
 * [timestampMs] is clock-offset corrected epoch ms; [rawTimestampMs] is the uncorrected one.
 * [accTsMs]/[gyroTsMs] are hardware event times in the corrected domain, 0 = unknown.
 * [sampleKind] is 0 for a fresh reading, 1 for a held (zero-order-hold) repeat.
 */
data class SensorPacket(
    val accX: Float = 0f,
    val accY: Float = 0f,
    val accZ: Float = 0f,
    val gyroX: Float = 0f,
    val gyroY: Float = 0f,
    val gyroZ: Float = 0f,
    val timestampMs: Long = 0,
    val sequenceNumber: Long = 0,
    val deviceId: String = "",
    val schemaVersion: Int = 0,
    val rawTimestampMs: Long = 0,
    val accTsMs: Long = 0,
    val gyroTsMs: Long = 0,
    val sampleKind: Int = 0,
) {
    fun encode(): ByteArray = ProtoWriter(96)
        .floatField(1, accX)
        .floatField(2, accY)
        .floatField(3, accZ)
        .floatField(4, gyroX)
        .floatField(5, gyroY)
        .floatField(6, gyroZ)
        .varintField(7, timestampMs)
        .varintField(8, sequenceNumber)
        .stringField(9, deviceId)
        .varintField(10, schemaVersion)
        .varintField(11, rawTimestampMs)
        .varintField(12, accTsMs)
        .varintField(13, gyroTsMs)
        .varintField(14, sampleKind)
        .toByteArray()

    companion object {
        /** The schema version every packet this app sends carries. */
        const val SCHEMA_VERSION = 2

        fun decode(data: ByteArray): SensorPacket {
            val r = ProtoReader(data)
            var p = SensorPacket()
            while (!r.isAtEnd) {
                val tag = r.readTag()
                val field = ProtoReader.fieldOf(tag)
                when (val wire = ProtoReader.wireOf(tag)) {
                    WIRE_FIXED32 -> {
                        val v = r.readFloat()
                        p = when (field) {
                            1 -> p.copy(accX = v)
                            2 -> p.copy(accY = v)
                            3 -> p.copy(accZ = v)
                            4 -> p.copy(gyroX = v)
                            5 -> p.copy(gyroY = v)
                            6 -> p.copy(gyroZ = v)
                            else -> p
                        }
                    }
                    WIRE_VARINT -> {
                        val v = r.readVarint64()
                        p = when (field) {
                            7 -> p.copy(timestampMs = v)
                            8 -> p.copy(sequenceNumber = v)
                            10 -> p.copy(schemaVersion = v.toInt())
                            11 -> p.copy(rawTimestampMs = v)
                            12 -> p.copy(accTsMs = v)
                            13 -> p.copy(gyroTsMs = v)
                            14 -> p.copy(sampleKind = v.toInt())
                            else -> p
                        }
                    }
                    WIRE_LENGTH_DELIMITED -> {
                        val s = r.readString()
                        if (field == 9) p = p.copy(deviceId = s)
                    }
                    else -> if (!r.skipField(wire)) return p
                }
            }
            return p
        }
    }
}

// ── DeviceRegister ──────────────────────────────────────────────────────────

/**
 * `shared_contracts/sensor_packet.proto` DeviceRegister. Must be the FIRST binary frame on
 * `/ws/control`; the backend closes with 4001 if it is missing or invalid (no device_id or
 * no device_role) and with 4002 after an ERROR_ALERT when the role is already taken.
 */
data class DeviceRegister(
    val deviceId: String = "",
    val deviceRole: String = "",
    val deviceModel: String = "",
    val androidVersion: String = "",
    val appVersion: String = "",
    val schemaVersion: Int = SCHEMA_VERSION,
) {
    fun encode(): ByteArray = ProtoWriter(128)
        .stringField(1, deviceId)
        .stringField(2, deviceRole)
        .stringField(3, deviceModel)
        .stringField(4, androidVersion)
        .stringField(5, appVersion)
        .varintField(6, schemaVersion)
        .toByteArray()

    companion object {
        const val SCHEMA_VERSION = 1

        fun decode(data: ByteArray): DeviceRegister {
            val r = ProtoReader(data)
            var m = DeviceRegister()
            while (!r.isAtEnd) {
                val tag = r.readTag()
                val field = ProtoReader.fieldOf(tag)
                when (val wire = ProtoReader.wireOf(tag)) {
                    WIRE_LENGTH_DELIMITED -> {
                        val s = r.readString()
                        m = when (field) {
                            1 -> m.copy(deviceId = s)
                            2 -> m.copy(deviceRole = s)
                            3 -> m.copy(deviceModel = s)
                            4 -> m.copy(androidVersion = s)
                            5 -> m.copy(appVersion = s)
                            else -> m
                        }
                    }
                    WIRE_VARINT -> {
                        val v = r.readVarint64()
                        if (field == 6) m = m.copy(schemaVersion = v.toInt())
                    }
                    else -> if (!r.skipField(wire)) return m
                }
            }
            return m
        }
    }
}

// ── Command ─────────────────────────────────────────────────────────────────

object CommandType {
    const val PING = 0
    const val PONG = 1
    const val START_SESSION = 2
    const val STOP_SESSION = 3
    const val SET_LABEL = 4
    const val ACK = 5
    const val CLOCK_SYNC = 6
    const val ERROR_ALERT = 7

    fun name(type: Int): String = when (type) {
        PING -> "PING"
        PONG -> "PONG"
        START_SESSION -> "START_SESSION"
        STOP_SESSION -> "STOP_SESSION"
        SET_LABEL -> "SET_LABEL"
        ACK -> "ACK"
        CLOCK_SYNC -> "CLOCK_SYNC"
        ERROR_ALERT -> "ERROR_ALERT"
        else -> "UNKNOWN($type)"
    }
}

/** `shared_contracts/commands.proto`. [payload] is a JSON string, schema per [type]. */
data class Command(
    val type: Int = CommandType.PING,
    val payload: String = "",
    val issuedAtMs: Long = 0,
    val commandId: String = "",
) {
    fun encode(): ByteArray = ProtoWriter(64 + payload.length)
        .varintField(1, type)
        .stringField(2, payload)
        .varintField(3, issuedAtMs)
        .stringField(4, commandId)
        .toByteArray()

    companion object {
        fun decode(data: ByteArray): Command {
            val r = ProtoReader(data)
            var c = Command()
            while (!r.isAtEnd) {
                val tag = r.readTag()
                val field = ProtoReader.fieldOf(tag)
                when (val wire = ProtoReader.wireOf(tag)) {
                    WIRE_VARINT -> {
                        val v = r.readVarint64()
                        c = when (field) {
                            1 -> c.copy(type = v.toInt())
                            3 -> c.copy(issuedAtMs = v)
                            else -> c
                        }
                    }
                    WIRE_LENGTH_DELIMITED -> {
                        val s = r.readString()
                        c = when (field) {
                            2 -> c.copy(payload = s)
                            4 -> c.copy(commandId = s)
                            else -> c
                        }
                    }
                    else -> if (!r.skipField(wire)) return c
                }
            }
            return c
        }
    }
}

// ── Command payload schemas ─────────────────────────────────────────────────

private val json = Json { ignoreUnknownKeys = true; isLenient = true }

/** Returns null for an empty/unparseable payload, which means "no information". */
private fun parseObject(payload: String): JsonObject? =
    if (payload.isBlank()) {
        null
    } else {
        try {
            json.parseToJsonElement(payload) as? JsonObject
        } catch (_: Exception) {
            null
        }
    }

/** A JSON string value, or null when absent, not a string, or empty. */
private fun JsonObject.text(key: String): String? {
    val v = this[key] as? JsonPrimitive ?: return null
    val s = if (v.isString) v.content else v.content.trim('"')
    return s.ifEmpty { null }
}

/** A JSON number value, or null when absent or not numeric. */
private fun JsonObject.number(key: String): Long? {
    val v = this[key] as? JsonPrimitive ?: return null
    v.content.toLongOrNull()?.let { return it }
    return v.content.toDoubleOrNull()?.toLong()
}

/**
 * PONG doubles as the authoritative session-state heartbeat. Every field is optional and an
 * empty payload means "no information" (an older backend), so nothing here may be assumed.
 */
data class PongPayload(
    val state: String?,
    val sessionId: String?,
    val lateSid: String?,
    val telemetryPackets: Long?,
    val telemetryAgeMs: Long?,
) {
    companion object {
        fun parse(payload: String): PongPayload? {
            val o = parseObject(payload) ?: return null
            return PongPayload(
                state = o.text("state"),
                sessionId = o.text("session_id"),
                lateSid = o.text("late_sid"),
                telemetryPackets = o.number("telemetry_packets"),
                telemetryAgeMs = o.number("telemetry_age_ms"),
            )
        }
    }
}

data class StartSessionPayload(
    val sessionId: String?,
    val scheduledStartMs: Long?,
    val subject: String?,
    val sessionTag: String?,
    val operator: String?,
) {
    companion object {
        fun parse(payload: String): StartSessionPayload? {
            val o = parseObject(payload) ?: return null
            return StartSessionPayload(
                sessionId = o.text("session_id"),
                scheduledStartMs = o.number("scheduled_start_ms"),
                subject = o.text("subject"),
