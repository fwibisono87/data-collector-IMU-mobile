data class SetLabelPayload(val labelId: Int?, val labelName: String?) {
    companion object {
        fun parse(payload: String): SetLabelPayload? {
            val o = parseObject(payload) ?: return null
            return SetLabelPayload(
                labelId = o.number("label_id")?.toInt(),
                labelName = o.text("label_name"),
            )
        }
    }
}

data class ClockSyncResponse(val t0Ms: Long?, val t1Ms: Long?, val t2Ms: Long?) {
    companion object {
        fun parse(payload: String): ClockSyncResponse? {
            val o = parseObject(payload) ?: return null
            return ClockSyncResponse(o.number("t0_ms"), o.number("t1_ms"), o.number("t2_ms"))
        }
    }
}

data class ErrorAlertPayload(val code: String?, val detail: String?) {
    companion object {
        /** Role-collision rejection code; the backend sends it just before close code 4002. */
        const val ROLE_COLLISION = "ROLE_COLLISION"

        fun parse(payload: String): ErrorAlertPayload {
            val o = parseObject(payload)
            return ErrorAlertPayload(o?.text("code"), o?.text("detail"))
        }
    }
}

/** CLOCK_SYNC request payload: `{"t0_ms":<phone epoch ms>}`. */
fun clockSyncRequestPayload(t0Ms: Long): String = buildJsonObject { put("t0_ms", t0Ms) }.toString()
