"""The dashboard↔backend contract as Pydantic v2 models.

This module is the only place these shapes are written down. ``docs/rebuild/API.md``
documents them; ``master_backend/app/api/schema.json`` (generated by
``export_schema.py``) carries them to the dashboard, which generates its TypeScript
types from it. If a model here changes, regenerate the JSON Schema and the dashboard
types together — the freshness tests on both sides fail otherwise.

Conventions taken from the API document:

* times are epoch milliseconds and every such field ends in ``_ms``;
* sizes are bytes and end in ``_bytes`` (the pre-existing ``bytes`` field in
  ``SessionFile`` keeps its contract name);
* ``null`` is meaningful and is spelled ``| None`` in this module, never "absent";
* inbound models ignore unknown fields (``extra="ignore"``) so a newer dashboard can
  talk to an older backend within the same protocol version. No model forbids extras.
"""
from __future__ import annotations

from typing import Annotated, Any, Literal, Union

from pydantic import BaseModel, ConfigDict, Field

# ---------------------------------------------------------------------------
# constrained scalars
# ---------------------------------------------------------------------------

#: One three-axis sample: exactly three floats, x/y/z.
TripleFloat = Annotated[list[float], Field(min_length=3, max_length=3)]

#: Label ids are numeric and stay in 0..50 (0 = baseline). See SPEC.md §2.
LabelId = Annotated[int, Field(ge=0, le=50)]

SessionState = Literal["IDLE", "RECORDING", "FINALIZING", "VALIDATING", "ERROR"]
CameraBackend = Literal["dshow", "v4l2", "fake"]
CameraState = Literal["opening", "live", "lost", "error"]
DriftVerdict = Literal["OK", "CHECK", "MOVED", "NO_SIGNAL", "MISSING", "RESOLUTION_CHANGED"]
FinalizeStepName = Literal[
    "close_writers", "cameras", "consolidate", "validate", "bundle", "package", "late_window"
]
FinalizeStepStatus = Literal["pending", "running", "done", "failed", "skipped"]
ConsolidationState = Literal["current", "pending_phone_data", "not_needed"]
NoticeLevel = Literal["info", "warn", "error"]
SessionVerdict = Literal["PASS", "PARTIAL", "FAIL", "UNKNOWN", "NONE"]

#: Inbound body models accept unknown fields; fields the sender cannot know yet may be
#: added by a newer dashboard without breaking an older backend.
_INBOUND = ConfigDict(extra="ignore")


# ---------------------------------------------------------------------------
# shared models
# ---------------------------------------------------------------------------
class Issue(BaseModel):
    """One actionable problem or warning. ``subject`` identifies what it is about
    (device_id, cam_id or a form field name)."""

    code: str
    message: str
    subject: str | None = None


class SessionLabel(BaseModel):
    """The label that is active right now."""

    id: int
    name: str
    since_ms: int


class SessionInfo(BaseModel):
    """The session that is recording or finalising."""

    session_id: str
    subject: str
    session_tag: str
    operator: str
    started_at_ms: int
    scheduled_start_ms: int
    label: SessionLabel


class Draft(BaseModel):
    """Server-side copy of the Setup form, so every browser shows the same values."""

    subject: str
    session_tag: str
    operator: str
    updated_at_ms: int


class Phone(BaseModel):
    """One connected phone and its health."""

    device_id: str
    role: str
    model: str
    app_version: str
    online: bool
    offline_since_ms: int | None
    rate_hz: float
    true_hz_avg: float
    packets: int
    telemetry_age_ms: int | None
    buffering: bool


class CameraDevice(BaseModel):
    """A device the camera backend can open."""

    device_key: str
    label: str
    backend: CameraBackend


class Drift(BaseModel):
    """Result of the calibration comparison against the active reference."""

    verdict: DriftVerdict
    dx_px: float
    dy_px: float
    shift_pct: float
    score: float
    confidence: float
    at_ms: int


class Camera(BaseModel):
    """One selected camera slot (cam1..cam5)."""

    cam_id: str
    device_key: str
    label: str
    state: CameraState
    recording: bool
    width: int | None
    height: int | None
    fps: float | None
    dropped_frames: int
    error: str | None
    drift: Drift | None


class FinalizeStep(BaseModel):
    """One step of the finalize job. ``detail`` is human-readable error/extra text."""

    name: FinalizeStepName
    status: FinalizeStepStatus
    started_at_ms: int | None
    ended_at_ms: int | None
    detail: str | None


class FinalizeProgress(BaseModel):
    """Finalize progress for one session; also the payload of the ``finalize`` WS message."""

    session_id: str
    steps: list[FinalizeStep]


class Notice(BaseModel):
    """A server-side notice. Unresolved & undismissed notices are in the snapshot."""

    id: str
    level: NoticeLevel
    code: str
    message: str
    session_id: str | None
    created_at_ms: int
    resolved: bool


class Readiness(BaseModel):
    """What START needs (blockers) and what it merely records (warnings)."""

    blockers: list[Issue]
    warnings: list[Issue]


class DiskInfo(BaseModel):
    path: str
    free_bytes: int


class CalibrationState(BaseModel):
    active_ref_id: str | None


class Snapshot(BaseModel):
    """The whole dashboard state. Always sent whole; the dashboard never patches."""

    build_id: str
    server_time_ms: int
    state: SessionState
    session: SessionInfo | None
    last_session_id: str | None
    draft: Draft
    phones: list[Phone]
    cameras: list[Camera]
    readiness: Readiness
    finalize: FinalizeProgress | None
    notices: list[Notice]
    disk: DiskInfo
    calibration: CalibrationState


class SessionSummary(BaseModel):
    """One row of the Sessions history (and the head of SessionDetail)."""

    session_id: str
    subject: str
    session_tag: str
    operator: str
    started_at_ms: int
    ended_at_ms: int | None
    duration_s: float | None
    phones: list[str]
    cameras: list[str]
    verdict: SessionVerdict
    folder: str
    zip_path: str | None
    zip_bytes: int | None
    outstanding_uploads: int
    notices: int


class SessionFile(BaseModel):
    """One file in the session folder, as listed in the Done/Sessions view."""

    name: str
    bytes: int
    kind: str


class LateRows(BaseModel):
    """Rows that arrived inside the late window for one device."""

    device_id: str
    role: str
    rows: int


class UploadStatus(BaseModel):
    """Phone rescue upload progress for one device."""

    device_id: str
    role: str
    received_bytes: int
    total_bytes: int | None
    complete: bool
    verified: bool


class ConsolidationStatus(BaseModel):
    """Is the session's consolidation current? (Done view's Consolidation row.)

    ``state`` is the row: ``not_needed`` for a whole session, ``pending_phone_data``
    when late rows / rescue uploads are not merged yet, ``current`` otherwise.
    ``can_consolidate`` is the ported ``canConsolidate`` from the old end-session modal
    and decides whether "Consolidate now" is offered.
    """

    state: ConsolidationState
    detail: str
    can_consolidate: bool
    whole: bool
    late_pending: bool
    recovery_pending: bool
    uploads_in_progress: bool
    rescue_uploads: int
    late_rows: int


class SessionDetail(SessionSummary):
    """A SessionSummary plus everything the Done view shows."""

    finalize: list[FinalizeStep]
    integrity_report: dict[str, Any] | None
    files: list[SessionFile]
    late: list[LateRows]
    uploads: list[UploadStatus]
    consolidation: ConsolidationStatus | None = None


class ReferenceCamera(BaseModel):
    """One still inside a calibration reference set (CALIBRATION.md)."""

    device_key: str
    label: str
    cam_id_at_capture: str
    file: str
    width: int
    height: int
    frame_arrival_ms: int
    skew_ms: int


class Reference(BaseModel):
    """``reference.json`` plus the URLs the dashboard renders thumbnails from.

    ``thumb_urls`` maps ``device_key`` to the full-resolution still URL
    (``/api/calibration/references/<ref_id>/<key_slug>.jpg``); ``cameras[].file``
    stays the on-disk filename from the frozen-ish calibration layout.
    """

    ref_id: str
    name: str
    created_at_ms: int
    trigger_ms: int
    cameras: list[ReferenceCamera]
    thumb_urls: dict[str, str] = Field(default_factory=dict)


class CompareCamera(Drift):
    """A Drift verdict attributed to one camera."""

    device_key: str
    cam_id: str


class CompareResult(BaseModel):
    """Result of ``GET /api/calibration/compare`` and the ``calibration.drift`` message."""

    ref_id: str
    at_ms: int
    cameras: list[CompareCamera]


class ErrorBody(BaseModel):
    code: str
    message: str
    details: dict[str, Any] | None


class ErrorResponse(BaseModel):
    error: ErrorBody


# ---------------------------------------------------------------------------
# REST request bodies (inbound: ignore unknown fields)
# ---------------------------------------------------------------------------
class DraftUpdate(BaseModel):
    """``PUT /api/session/draft``. ``None`` means "keep the current value"."""

    model_config = _INBOUND

    subject: str | None = None
    session_tag: str | None = None
    operator: str | None = None


class StartRequest(BaseModel):
    """``POST /api/session/start`` — the body is empty today."""

    model_config = _INBOUND


class StopRequest(BaseModel):
    model_config = _INBOUND

    reason: str | None = None


class LabelRequest(BaseModel):
    model_config = _INBOUND

    label_id: LabelId


class CameraSelectionItem(BaseModel):
    """One selected device. ``cam_id`` is optional: slots are assigned in list order."""

    model_config = _INBOUND

    device_key: str
    cam_id: str | None = None


class CameraSelectionRequest(BaseModel):
    model_config = _INBOUND

    cameras: list[CameraSelectionItem] = Field(max_length=5)


class ReferenceCreate(BaseModel):
    """``POST /api/calibration/references``; the name is generated when absent."""

    model_config = _INBOUND

    name: str | None = None


class ReferenceRename(BaseModel):
    model_config = _INBOUND

    name: str


# ---------------------------------------------------------------------------
# REST response bodies
# ---------------------------------------------------------------------------
class StartResponse(BaseModel):
    session_id: str
    scheduled_start_ms: int
    warnings: list[Issue]


class StopResponse(BaseModel):
    session_id: str


class LabelResponse(BaseModel):
    label_id: int
    since_ms: int


class SessionList(BaseModel):
    sessions: list[SessionSummary]
    next: str | None


class PackageResponse(BaseModel):
    zip_path: str


class CameraSelectionResponse(BaseModel):
    cameras: list[Camera]


class DeviceList(BaseModel):
    devices: list[CameraDevice]


class ReferenceList(BaseModel):
    references: list[Reference]
    active_ref_id: str | None


class EmptyResponse(BaseModel):
    """The documented ``{}`` body of dismiss / open-folder / activate / deactivate."""


# ---------------------------------------------------------------------------
# WebSocket server -> client
# ---------------------------------------------------------------------------
class SnapshotMsg(BaseModel):
    type: Literal["snapshot"] = "snapshot"
    data: Snapshot


class LiveSample(BaseModel):
    """Latest IMU sample of one phone. ``acc`` is in g, ``gyro`` in deg/s."""

    acc: TripleFloat
    gyro: TripleFloat
    ts_ms: int


class LiveData(BaseModel):
    t_ms: int
    phones: dict[str, LiveSample]


class LiveMsg(BaseModel):
    type: Literal["live"] = "live"
    data: LiveData


class FinalizeMsg(BaseModel):
    type: Literal["finalize"] = "finalize"
    data: FinalizeProgress


class DriftMsg(BaseModel):
    type: Literal["calibration.drift"] = "calibration.drift"
    data: CompareResult


class AckMsg(BaseModel):
    type: Literal["ack"] = "ack"
    req_id: str
    ok: bool
    error: ErrorBody | None = None


# ---------------------------------------------------------------------------
# WebSocket client -> server (inbound: ignore unknown fields)
# ---------------------------------------------------------------------------
class WatchMsg(BaseModel):
    """Start receiving ``calibration.drift``. ``ref_id`` may be a real id or "active"."""

    model_config = _INBOUND

    type: Literal["calibration.watch"] = "calibration.watch"
    ref_id: str
    req_id: str | None = None


class UnwatchMsg(BaseModel):
    model_config = _INBOUND

    type: Literal["calibration.unwatch"] = "calibration.unwatch"
    req_id: str | None = None


class PingMsg(BaseModel):
    model_config = _INBOUND

    type: Literal["ping"] = "ping"
    req_id: str


ServerMessage = Annotated[
    Union[SnapshotMsg, LiveMsg, FinalizeMsg, DriftMsg, AckMsg],
    Field(discriminator="type"),
]
"""Every message the backend may push on ``/ws/ui``."""

ClientMessage = Annotated[
    Union[WatchMsg, UnwatchMsg, PingMsg],
    Field(discriminator="type"),
]
"""Every message a dashboard may send on ``/ws/ui``."""